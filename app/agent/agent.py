def run_agent(
    user_message: str,
    conversation_history: list[dict] | None = None,
    student_id: str | None = None,
) -> dict:
    """
    Run the MindSync Groq agent.

    Parameters
    ----------
    user_message:
        Current message from the student.

    conversation_history:
        Previous conversation messages.

    student_id:
        Authenticated student ID obtained from the JWT.

    Returns
    -------
    dict
        {
            "reply": str,
            "history": list,
            "tool_calls": list,
            "message_count": int,
            "message_types": list
        }
    """

    # ---------------------------------------------------------------
    # Validate authenticated student identity
    # ---------------------------------------------------------------

    if not student_id or not student_id.strip():

        raise ValueError(
            "Authenticated student identity is required."
        )

    student_id = student_id.strip()

    messages: list[BaseMessage] = []

    messages = []

    for message in conversation_history or []:

        if not isinstance(message, dict):
            continue

        role = message.get("role")
        content = message.get("content", "")

        if role not in {"user", "assistant"}:
            continue

        if not isinstance(content, str):
            continue

        content = content.strip()

        if not content:
            continue

        if role == "user":

            messages.append(
                HumanMessage(
                    content=content,
                )
            )

        elif role == "assistant":

            messages.append(
                AIMessage(
                    content=content,
                )
            )

    # ---------------------------------------------------------------
    # CURRENT USER MESSAGE
    # ---------------------------------------------------------------

    messages.append(
        {
            "messages": messages,
        },
        context=AgentContext(
            student_id=student_id,
        ),
        config={
            "recursion_limit": 10,
        },
    )

    # ---------------------------------------------------------------
    # TOOL CALL LOG
    # ---------------------------------------------------------------

    reply = ""

    for message in reversed(final_messages):

        if not isinstance(message, AIMessage):
            continue

        # Ignore AI messages that are requesting tools.
        if message.tool_calls:
            continue

        if isinstance(message.content, str):

            reply = message.content

        elif isinstance(message.content, list):

            text_parts = []

            for block in message.content:

                if (
                    isinstance(block, dict)
                    and block.get("type") == "text"
                ):
                    text_parts.append(
                        block.get("text", "")
                    )

            reply = "".join(text_parts)

